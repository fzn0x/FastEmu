//! Java stub sources of every class the runtime registers, and the jar
//! javac compiles from them.
//!
//! Test MIDlets compile against this jar as their boot class path, so they
//! see exactly the classes, members, flags and constant values FastEmu
//! provides: a test that calls something FastEmu lacks does not compile.
//! The `throws` clauses come from the API inventory (the runtime does not
//! record them): each checked exception its Throws column names.
//!
//! A stub keeps what javac needs and nothing else: the declaration, the
//! fields with their constants, and methods whose bodies throw. Where the
//! runtime's classes cannot be written as Java as they are (a class that
//! leaves an abstract method unimplemented, two methods that differ only
//! in their return type), the stub is adjusted so it still compiles and
//! the adjustment is reported as a warning.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use fastemu_jvm::classfile::access;
use fastemu_jvm::descriptor::MethodDescriptor;

use super::inventory::Inventory;
use super::java;
use super::runtime::{Class, Method, Runtime};

/// The name of the jar in the output folder.
pub const JAR: &str = "fastemu-stubs.jar";

/// The first line of every stub source.
const HEADER: &str = "// Generated by `cargo xtask stubs` from the classes FastEmu registers.";

/// Stub sources by path (`java/lang/Object.java`), and what had to be
/// adjusted to write them.
pub struct Sources {
    pub files: BTreeMap<String, String>,
    pub warnings: Vec<String>,
}

/// A constructor as the stub declares it.
#[derive(Clone)]
struct Ctor {
    desc: String,
    flags: u16,
}

/// Everything the writer needs about the whole class set.
struct Plan<'a> {
    runtime: &'a Runtime,
    /// The constructors of each class, with one added where the runtime
    /// declares none (Java would add a public one otherwise).
    ctors: HashMap<&'a str, Vec<Ctor>>,
    /// The checked exceptions of each method, by `class.name desc`.
    throws: HashMap<String, Vec<String>>,
    warnings: Vec<String>,
}

fn visibility(flags: u16) -> &'static str {
    if flags & access::PUBLIC != 0 {
        "public "
    } else if flags & access::PROTECTED != 0 {
        "protected "
    } else if flags & access::PRIVATE != 0 {
        "private "
    } else {
        ""
    }
}

fn is_private(flags: u16) -> bool {
    flags & access::PRIVATE != 0
}

fn is_static(flags: u16) -> bool {
    flags & access::STATIC != 0
}

fn key(class: &str, name: &str, desc: &str) -> String {
    format!("{class}.{name}{desc}")
}

impl<'a> Plan<'a> {
    fn new(runtime: &'a Runtime, inventory: &Inventory) -> Self {
        let mut plan = Self {
            runtime,
            ctors: HashMap::new(),
            throws: HashMap::new(),
            warnings: Vec::new(),
        };
        plan.plan_ctors();
        plan.plan_throws(inventory);
        plan
    }

    /// The constructors of every class. A class the runtime gives none
    /// gets a no-argument one only its stub subclasses can reach.
    fn plan_ctors(&mut self) {
        let runtime = self.runtime;
        for class in runtime.classes.values() {
            if class.is_interface() {
                continue;
            }
            let mut ctors: Vec<Ctor> = class
                .methods
                .iter()
                .filter(|m| m.name == "<init>")
                .map(|m| Ctor {
                    desc: m.desc.clone(),
                    flags: m.flags,
                })
                .collect();
            if ctors.is_empty() {
                let subclasses: Vec<&Class> = runtime
                    .classes
                    .values()
                    .filter(|c| c.super_name.as_deref() == Some(&class.name))
                    .collect();
                let flags = if subclasses.is_empty() {
                    access::PRIVATE
                } else if subclasses.iter().all(|c| c.package() == class.package()) {
                    0
                } else {
                    access::PROTECTED
                };
                ctors.push(Ctor {
                    desc: "()V".to_owned(),
                    flags,
                });
            }
            self.ctors.insert(&class.name, ctors);
        }
    }

    /// The internal name of the exception `name` (simple or qualified)
    /// that a member of `class` throws.
    fn exception(&self, class: &Class, name: &str) -> Option<String> {
        if name.contains('.') {
            let internal = name.replace('.', "/");
            return self.runtime.get(&internal).map(|c| c.name.clone());
        }
        let candidates: Vec<&Class> = self
            .runtime
            .classes
            .values()
            .filter(|c| {
                c.simple_name() == name && self.runtime.is_subtype(&c.name, "java/lang/Throwable")
            })
            .collect();
        [class.package(), "java/lang", "java/io"]
            .iter()
            .find_map(|p| candidates.iter().find(|c| c.package() == *p))
            .or_else(|| (candidates.len() == 1).then(|| &candidates[0]))
            .map(|c| c.name.clone())
    }

    /// The checked exceptions each method declares: those the inventory
    /// names, less any a method it overrides does not allow.
    fn plan_throws(&mut self, inventory: &Inventory) {
        let runtime = self.runtime;
        for class in runtime.classes.values() {
            for m in &class.methods {
                let Some(member) = inventory.member(&class.name, &m.name, &m.desc) else {
                    continue;
                };
                let mut names = Vec::new();
                for name in &member.throws {
                    match self.exception(class, name) {
                        Some(e) if runtime.is_checked_exception(&e) => names.push(e),
                        Some(_) => {}
                        None => self.warnings.push(format!(
                            "{}.{}{}: throws {name}, which FastEmu lacks",
                            class.name, m.name, m.desc
                        )),
                    }
                }
                if !names.is_empty() {
                    self.throws
                        .insert(key(&class.name, &m.name, &m.desc), names);
                }
            }
        }
        // An override may not declare a checked exception the method it
        // overrides does not; drop those, until nothing changes.
        loop {
            let mut changed = false;
            for class in runtime.classes.values() {
                for m in &class.methods {
                    let k = key(&class.name, &m.name, &m.desc);
                    let Some(own) = self.throws.get(&k).cloned() else {
                        continue;
                    };
                    let mut kept = own.clone();
                    for parent in self.overridden(class, m) {
                        let allowed = self
                            .throws
                            .get(&key(&parent.name, &m.name, &m.desc))
                            .cloned()
                            .unwrap_or_default();
                        kept.retain(|e| allowed.iter().any(|a| runtime.is_subtype(e, a)));
                    }
                    if kept != own {
                        for dropped in own.iter().filter(|e| !kept.contains(e)) {
                            self.warnings.push(format!(
                                "{k}: throws {dropped}, which the method it overrides does not"
                            ));
                        }
                        changed = true;
                        self.throws.insert(k, kept);
                    }
                }
            }
            if !changed {
                break;
            }
        }
    }

    /// The classes and interfaces above `class` that declare an instance
    /// method `m` overrides.
    fn overridden(&self, class: &Class, m: &Method) -> Vec<&'a Class> {
        if m.name == "<init>" || is_static(m.flags) || is_private(m.flags) {
            return Vec::new();
        }
        let runtime = self.runtime;
        runtime
            .superclasses(&class.name)
            .into_iter()
            .skip(1)
            .chain(runtime.all_interfaces(&class.name))
            .filter(|c| {
                c.method(&m.name, &m.desc)
                    .is_some_and(|p| !is_static(p.flags) && !is_private(p.flags))
            })
            .collect()
    }

    /// The `throws` clause of a method, with a leading space.
    fn throws_clause(&self, class: &str, m: &Method) -> String {
        match self.throws.get(&key(class, &m.name, &m.desc)) {
            Some(names) if !names.is_empty() => {
                let list: Vec<String> = names.iter().map(|n| java::binary(n)).collect();
                format!(" throws {}", list.join(", "))
            }
            _ => String::new(),
        }
    }

    /// The abstract methods a concrete class inherits and nothing in its
    /// class chain implements. Calling one throws `AbstractMethodError`
    /// in FastEmu; the stub gives it a body so javac accepts the class.
    fn unimplemented(&self, class: &Class) -> Vec<Method> {
        let runtime = self.runtime;
        let chain = runtime.superclasses(&class.name);
        let implemented = |m: &Method| {
            chain.iter().any(|c| {
                c.method(&m.name, &m.desc)
                    .is_some_and(|own| own.flags & access::ABSTRACT == 0 && !is_static(own.flags))
            }) || runtime
                .get("java/lang/Object")
                .and_then(|o| o.method(&m.name, &m.desc))
                .is_some_and(|own| own.flags & access::PUBLIC != 0)
        };
        let mut missing: Vec<Method> = Vec::new();
        for above in chain
            .iter()
            .skip(1)
            .copied()
            .chain(runtime.all_interfaces(&class.name))
        {
            for m in &above.methods {
                let is_abstract = m.flags & access::ABSTRACT != 0
                    || (above.is_interface() && !is_static(m.flags) && m.name != "<clinit>");
                if is_abstract
                    && !implemented(m)
                    && !missing.iter().any(|x| x.name == m.name && x.desc == m.desc)
                {
                    missing.push(Method {
                        name: m.name.clone(),
                        desc: m.desc.clone(),
                        flags: m.flags & !access::ABSTRACT & !access::PROTECTED | access::PUBLIC,
                    });
                }
            }
        }
        missing
    }

    /// The `super(...)` call a constructor of `class` makes.
    fn super_call(&mut self, class: &Class) -> String {
        let Some(parent) = class.super_name.as_deref() else {
            return String::new();
        };
        let parent_package = parent.rsplit_once('/').map_or("", |(p, _)| p);
        let reachable = |c: &&Ctor| {
            c.flags & (access::PUBLIC | access::PROTECTED) != 0
                || (!is_private(c.flags) && parent_package == class.package())
        };
        let ctors = self.ctors.get(parent).cloned().unwrap_or_default();
        let chosen = ctors
            .iter()
            .filter(reachable)
            .min_by_key(|c| c.desc != "()V")
            .cloned();
        let Some(ctor) = chosen else {
            self.warnings.push(format!(
                "{}: no constructor of {parent} is reachable from it",
                class.name
            ));
            return "        super();\n".to_owned();
        };
        let args: Vec<String> = MethodDescriptor::parse(&ctor.desc)
            .map(|d| d.params.iter().map(|p| java::placeholder(p)).collect())
            .unwrap_or_default();
        format!("        super({});\n", args.join(", "))
    }
}

fn params(types: &[String]) -> String {
    types
        .iter()
        .enumerate()
        .map(|(i, t)| format!("{t} p{i}"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The source of one class.
fn class_source(plan: &mut Plan<'_>, class: &Class) -> Result<String, String> {
    let mut out = String::new();
    let _ = writeln!(out, "{HEADER}");
    if !class.package().is_empty() {
        let _ = writeln!(out, "package {};", java::binary(class.package()));
    }
    out.push('\n');
    let mut head = visibility(class.flags).to_owned();
    if class.is_interface() {
        head.push_str("interface ");
    } else {
        if class.is_abstract() {
            head.push_str("abstract ");
        }
        if class.flags & access::FINAL != 0 {
            head.push_str("final ");
        }
        head.push_str("class ");
    }
    head.push_str(class.simple_name());
    let interfaces: Vec<String> = class.interfaces.iter().map(|i| java::binary(i)).collect();
    if class.is_interface() {
        if !interfaces.is_empty() {
            let _ = write!(head, " extends {}", interfaces.join(", "));
        }
    } else {
        if let Some(parent) = &class.super_name {
            let _ = write!(head, " extends {}", java::binary(parent));
        }
        if !interfaces.is_empty() {
            let _ = write!(head, " implements {}", interfaces.join(", "));
        }
    }
    let _ = writeln!(out, "{head} {{");
    write_fields(plan, class, &mut out)?;
    write_ctors(plan, class, &mut out)?;
    write_methods(plan, class, &mut out)?;
    out.push_str("}\n");
    Ok(out)
}

fn write_fields(plan: &mut Plan<'_>, class: &Class, out: &mut String) -> Result<(), String> {
    let mut seen: Vec<&str> = Vec::new();
    for f in &class.fields {
        if is_private(f.flags) {
            continue;
        }
        if seen.contains(&f.name.as_str()) {
            plan.warnings.push(format!(
                "{}: a second field {}, of type {}, left out",
                class.name, f.name, f.desc
            ));
            continue;
        }
        seen.push(&f.name);
        let flags = if class.is_interface() {
            access::PUBLIC | access::STATIC | access::FINAL
        } else {
            f.flags
        };
        let mut line = format!("    {}", visibility(flags));
        if is_static(flags) {
            line.push_str("static ");
        }
        let is_final = flags & access::FINAL != 0;
        if is_final {
            line.push_str("final ");
        }
        let _ = write!(line, "{} {}", java::type_name(&f.desc)?, f.name);
        if is_final {
            let value = match &f.constant {
                Some(c) if is_static(flags) => java::literal(&f.desc, c)
                    .map_err(|e| format!("{}.{}: {e}", class.name, f.name))?,
                _ => java::non_constant(&f.desc),
            };
            let _ = write!(line, " = {value}");
        }
        let _ = writeln!(out, "{line};");
    }
    Ok(())
}

fn write_ctors(plan: &mut Plan<'_>, class: &Class, out: &mut String) -> Result<(), String> {
    if class.is_interface() {
        return Ok(());
    }
    let ctors = plan
        .ctors
        .get(class.name.as_str())
        .cloned()
        .unwrap_or_default();
    for ctor in ctors {
        let (types, _) = java::method_types(&ctor.desc)?;
        let m = Method {
            name: "<init>".to_owned(),
            desc: ctor.desc.clone(),
            flags: ctor.flags,
        };
        let _ = writeln!(
            out,
            "    {}{}({}){} {{",
            visibility(ctor.flags),
            class.simple_name(),
            params(&types),
            plan.throws_clause(&class.name, &m)
        );
        out.push_str(&plan.super_call(class));
        out.push_str("    }\n");
    }
    Ok(())
}

fn write_methods(plan: &mut Plan<'_>, class: &Class, out: &mut String) -> Result<(), String> {
    let mut written: Vec<(String, Vec<String>)> = Vec::new();
    let mut methods: Vec<Method> = class
        .methods
        .iter()
        .filter(|m| !m.name.starts_with('<') && !is_private(m.flags))
        .filter(|m| m.flags & (access::BRIDGE | access::SYNTHETIC) == 0)
        .cloned()
        .collect();
    if !class.is_interface() && !class.is_abstract() {
        for m in &mut methods {
            if m.flags & access::ABSTRACT != 0 {
                plan.warnings.push(format!(
                    "{}.{}{}: abstract in a class that is not; the stub gives it a body",
                    class.name, m.name, m.desc
                ));
                m.flags &= !access::ABSTRACT;
            }
        }
        for m in plan.unimplemented(class) {
            plan.warnings.push(format!(
                "{}.{}{}: inherited abstract and not implemented; the stub gives it a body",
                class.name, m.name, m.desc
            ));
            methods.push(m);
        }
    }
    for m in &methods {
        let (types, ret) = java::method_types(&m.desc)?;
        if written.iter().any(|(n, t)| *n == m.name && *t == types) {
            plan.warnings.push(format!(
                "{}.{}{}: differs from another method only in its return type; left out",
                class.name, m.name, m.desc
            ));
            continue;
        }
        written.push((m.name.clone(), types.clone()));
        let mut line = format!("    {}", visibility(m.flags));
        let is_abstract =
            m.flags & access::ABSTRACT != 0 || (class.is_interface() && !is_static(m.flags));
        if is_abstract {
            line.push_str("abstract ");
        }
        if is_static(m.flags) {
            line.push_str("static ");
        }
        if m.flags & access::FINAL != 0 && !is_abstract {
            line.push_str("final ");
        }
        let _ = write!(
            line,
            "{ret} {}({}){}",
            m.name,
            params(&types),
            plan.throws_clause(&class.name, m)
        );
        if is_abstract {
            line.push(';');
        } else {
            line.push_str(" { throw null; }");
        }
        let _ = writeln!(out, "{line}");
    }
    Ok(())
}

/// The classes a descriptor names.
fn referenced(desc: &str) -> impl Iterator<Item = &str> {
    let mut rest = desc;
    std::iter::from_fn(move || {
        loop {
            let first = rest.chars().next()?;
            if first == 'L' {
                let (name, after) = rest[1..].split_once(';')?;
                rest = after;
                return Some(name);
            }
            rest = &rest[first.len_utf8()..];
        }
    })
}

/// `runtime` without what cannot link there: classes whose superclass or
/// an interface is missing, and members whose descriptor names a missing
/// class. A game cannot use those either.
fn usable(runtime: &Runtime, warnings: &mut Vec<String>) -> Runtime {
    let mut classes = runtime.classes.clone();
    loop {
        let missing: Vec<(String, String)> = classes
            .values()
            .filter_map(|c| {
                c.super_name
                    .iter()
                    .chain(&c.interfaces)
                    .find(|s| !classes.contains_key(*s))
                    .map(|s| (c.name.clone(), s.clone()))
            })
            .collect();
        if missing.is_empty() {
            break;
        }
        for (class, parent) in missing {
            warnings.push(format!(
                "{class}: extends {parent}, which FastEmu lacks; left out"
            ));
            classes.remove(&class);
        }
    }
    let names: Vec<String> = classes.keys().cloned().collect();
    let lacks = |desc: &str| {
        referenced(desc)
            .find(|r| !names.iter().any(|n| n == r))
            .map(str::to_owned)
    };
    for class in classes.values_mut() {
        let name = class.name.clone();
        class.fields.retain(|f| match lacks(&f.desc) {
            Some(r) => {
                warnings.push(format!(
                    "{name}.{}: of type {r}, which FastEmu lacks; left out",
                    f.name
                ));
                false
            }
            None => true,
        });
        class.methods.retain(|m| match lacks(&m.desc) {
            Some(r) => {
                warnings.push(format!(
                    "{name}.{}{}: uses {r}, which FastEmu lacks; left out",
                    m.name, m.desc
                ));
                false
            }
            None => true,
        });
    }
    Runtime { classes }
}

/// The stub sources of every class of `runtime`, with the `throws`
/// clauses `inventory` gives.
pub fn sources(runtime: &Runtime, inventory: &Inventory) -> Result<Sources, String> {
    let mut warnings = Vec::new();
    let runtime = &usable(runtime, &mut warnings);
    let mut plan = Plan::new(runtime, inventory);
    plan.warnings.splice(0..0, warnings);
    let mut files = BTreeMap::new();
    for class in runtime.classes.values() {
        let text = class_source(&mut plan, class)?;
        files.insert(format!("{}.java", class.name), text);
    }
    Ok(Sources {
        files,
        warnings: plan.warnings,
    })
}

/// A JDK tool, from `JAVA_HOME` first, then the `PATH`.
pub fn jdk_tool(name: &str) -> Option<PathBuf> {
    let exe = if cfg!(windows) {
        format!("{name}.exe")
    } else {
        name.to_owned()
    };
    if let Some(home) = std::env::var_os("JAVA_HOME") {
        let candidate = Path::new(&home).join("bin").join(&exe);
        if candidate.is_file() {
            return Some(candidate);
        }
    }
    let works = Command::new(name)
        .arg("-version")
        .output()
        .is_ok_and(|o| o.status.success());
    works.then(|| PathBuf::from(name))
}

/// The javac options for code compiled against the stubs: Java 8 class
/// files, with the stubs as the whole platform.
pub fn javac_options(boot: &Path) -> Vec<std::ffi::OsString> {
    let mut options: Vec<std::ffi::OsString> = [
        "-source",
        "8",
        "-target",
        "8",
        "-g",
        "-encoding",
        "UTF-8",
        "-nowarn",
        "-Xlint:-options",
        "-implicit:none",
        "-extdirs",
        "",
    ]
    .iter()
    .map(Into::into)
    .collect();
    options.push("-bootclasspath".into());
    options.push(boot.into());
    options
}

/// Runs `command`, and fails with its output when it fails.
pub fn run(command: &mut Command, what: &str) -> Result<(), String> {
    let output = command
        .output()
        .map_err(|e| format!("running {what}: {e}"))?;
    if output.status.success() {
        return Ok(());
    }
    Err(format!(
        "{what} failed:\n{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    ))
}

/// What [`build`] made.
pub struct Built {
    /// The stubs jar.
    pub jar: PathBuf,
    /// How many classes it holds.
    pub classes: usize,
    /// Whether javac ran (false when the sources had not changed).
    pub compiled: bool,
    pub warnings: Vec<String>,
}

/// Writes `files` under `dir`, removes other `.java` files there, and
/// returns whether anything changed.
fn sync(dir: &Path, files: &BTreeMap<String, String>) -> Result<bool, String> {
    let io = |path: &Path, e: std::io::Error| format!("{}: {e}", path.display());
    let mut changed = false;
    for (name, text) in files {
        let path = dir.join(name);
        if fs::read_to_string(&path).is_ok_and(|old| old == *text) {
            continue;
        }
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|e| io(parent, e))?;
        }
        fs::write(&path, text).map_err(|e| io(&path, e))?;
        changed = true;
    }
    let mut stale = Vec::new();
    java_files(dir, &mut stale);
    for path in stale {
        let name = path
            .strip_prefix(dir)
            .map(|p| p.to_string_lossy().replace('\\', "/"))
            .unwrap_or_default();
        if !files.contains_key(&name) {
            fs::remove_file(&path).map_err(|e| io(&path, e))?;
            changed = true;
        }
    }
    Ok(changed)
}

/// Every `.java` file under `dir`.
pub fn java_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            java_files(&path, out);
        } else if path.extension().is_some_and(|e| e == "java") {
            out.push(path);
        }
    }
    out.sort();
}

/// Writes the stub sources of the runtime under `out/src`, compiles them
/// into `out/classes` and packs `out/fastemu-stubs.jar`. Sources that did
/// not change since the last build are not compiled again. `api_dir` is
/// `docs/compat/api`.
pub fn build(out: &Path, api_dir: &Path) -> Result<Built, String> {
    let runtime = Runtime::load();
    let inventory = Inventory::load(api_dir)?;
    let sources = sources(&runtime, &inventory)?;
    let src = out.join("src");
    let jar = out.join(JAR);
    let changed = sync(&src, &sources.files)?;
    let built = |compiled| Built {
        jar: jar.clone(),
        classes: sources.files.len(),
        compiled,
        warnings: sources.warnings.clone(),
    };
    if !changed && jar.is_file() {
        return Ok(built(false));
    }
    // Gone as soon as the sources change, until the new one is packed: a
    // build that stops part way, even for want of a JDK, must never leave
    // the old jar beside the new sources, where the next build would take
    // it for an up-to-date one.
    let _ = fs::remove_file(&jar);
    let javac = jdk_tool("javac").ok_or("no javac in JAVA_HOME or on the PATH")?;
    let jar_tool = jdk_tool("jar").ok_or("no jar tool in JAVA_HOME or on the PATH")?;
    let classes = out.join("classes");
    let _ = fs::remove_dir_all(&classes);
    fs::create_dir_all(&classes).map_err(|e| format!("{}: {e}", classes.display()))?;
    let mut files = Vec::new();
    java_files(&src, &mut files);
    // The list goes in an argument file: the command line of every
    // class would be too long for Windows.
    let list = out.join("sources.txt");
    let quoted: Vec<String> = files
        .iter()
        .map(|f| format!("\"{}\"", f.display().to_string().replace('\\', "/")))
        .collect();
    fs::write(&list, quoted.join("\n")).map_err(|e| format!("{}: {e}", list.display()))?;
    let mut javac_command = Command::new(&javac);
    javac_command
        .args(javac_options(&classes))
        .arg("-d")
        .arg(&classes)
        .arg(format!("@{}", list.display()));
    run(&mut javac_command, "javac on the stubs")?;
    let mut jar_command = Command::new(&jar_tool);
    jar_command
        .arg("cf")
        .arg(&jar)
        .arg("-C")
        .arg(&classes)
        .arg(".");
    run(&mut jar_command, "jar")?;
    Ok(built(true))
}

#[cfg(test)]
mod tests {
    use super::*;
    use fastemu_jvm::{NativeClass, Value};

    fn sources_of(natives: &[NativeClass], inventory: &str) -> Sources {
        let runtime = Runtime::from_natives(natives);
        let inventory = Inventory {
            classes: super::super::inventory::parse("t.md", inventory),
            problems: Vec::new(),
        };
        sources(&runtime, &inventory).unwrap()
    }

    fn base() -> Vec<NativeClass> {
        vec![
            NativeClass::new("java/lang/Object").method("<init>", "()V", |_, _| Ok(Value::Void)),
            NativeClass::new("java/lang/String").final_class(),
            NativeClass::new("java/lang/Throwable").method(
                "<init>",
                "(Ljava/lang/String;)V",
                |_, _| Ok(Value::Void),
            ),
            NativeClass::new("java/lang/Exception")
                .extends("java/lang/Throwable")
                .method("<init>", "()V", |_, _| Ok(Value::Void)),
            NativeClass::new("java/io/IOException")
                .extends("java/lang/Exception")
                .method("<init>", "()V", |_, _| Ok(Value::Void)),
            NativeClass::new("java/lang/RuntimeException")
                .extends("java/lang/Exception")
                .method("<init>", "()V", |_, _| Ok(Value::Void)),
            NativeClass::new("java/lang/NullPointerException")
                .extends("java/lang/RuntimeException")
                .method("<init>", "()V", |_, _| Ok(Value::Void)),
        ]
    }

    #[test]
    fn a_class_keeps_its_api() {
        let mut natives = base();
        natives.push(
            NativeClass::new("a/b/Thing")
                .abstract_class()
                .constant("MAX", "I", Value::Int(7))
                .static_field("count", "I")
                .method_with("<init>", "(I)V", access::PROTECTED, |_, _| Ok(Value::Void))
                .method("read", "()I", |_, _| Ok(Value::Int(0)))
                .abstract_method("paint", "(Ljava/lang/String;)V"),
        );
        let inventory = "\
`public abstract class a.b.Thing`

Tier 1.

| T | Method | Descriptor | Flags | Since | Throws | Notes |
|---|---|---|---|---|---|---|
| 1 | `int read()` | `read()I` |  | 2.0 | `IOException` if it fails; `NullPointerException` |  |
";
        let sources = sources_of(&natives, inventory);
        let thing = &sources.files["a/b/Thing.java"];
        assert!(thing.contains("package a.b;"), "{thing}");
        assert!(thing.contains("public abstract class Thing extends java.lang.Object {"));
        assert!(thing.contains("    public static final int MAX = 7;"));
        assert!(thing.contains("    public static int count;"));
        assert!(thing.contains("    protected Thing(int p0) {\n        super();\n    }"));
        assert!(
            thing.contains("    public int read() throws java.io.IOException { throw null; }"),
            "{thing}"
        );
        assert!(thing.contains("    public abstract void paint(java.lang.String p0);"));
        assert!(sources.warnings.is_empty(), "{:?}", sources.warnings);
        // A constructor with arguments is called with typed placeholders.
        let throwable = &sources.files["java/lang/Exception.java"];
        assert!(
            throwable.contains("super((java.lang.String) null);"),
            "{throwable}"
        );
    }

    #[test]
    fn descriptors_name_their_classes() {
        let names: Vec<&str> = referenced("(ILjava/lang/Long;[[La/LList;)LZ;").collect();
        assert_eq!(names, ["java/lang/Long", "a/LList", "Z"]);
    }

    #[test]
    fn what_cannot_link_is_left_out() {
        let mut natives = base();
        natives.push(
            NativeClass::new("a/Screen")
                .method("<init>", "()V", |_, _| Ok(Value::Void))
                .method("getTicker", "()La/Ticker;", |_, _| Ok(Value::Ref(None)))
                .method("show", "()V", |_, _| Ok(Value::Void)),
        );
        natives.push(NativeClass::new("a/Alert").extends("a/Missing"));
        let sources = sources_of(&natives, "");
        let screen = &sources.files["a/Screen.java"];
        assert!(
            screen.contains("void show()") && !screen.contains("getTicker"),
            "{screen}"
        );
        assert!(!sources.files.contains_key("a/Alert.java"));
        assert_eq!(sources.warnings.len(), 2, "{:?}", sources.warnings);
    }

    #[test]
    fn what_java_cannot_say_is_adjusted_and_reported() {
        let mut natives = base();
        natives.push(NativeClass::interface("a/Shape").abstract_method("area", "()I"));
        natives.push(
            NativeClass::new("a/Square")
                .implements("a/Shape")
                .method("side", "()I", |_, _| Ok(Value::Int(0)))
                .method("side", "()J", |_, _| Ok(Value::Long(0))),
        );
        let sources = sources_of(&natives, "");
        let square = &sources.files["a/Square.java"];
        assert!(square.contains("    private Square() {"), "{square}");
        assert!(
            square.contains("public int area() { throw null; }"),
            "{square}"
        );
        assert!(!square.contains("long side()"), "{square}");
        assert_eq!(sources.warnings.len(), 2, "{:?}", sources.warnings);
    }
}
